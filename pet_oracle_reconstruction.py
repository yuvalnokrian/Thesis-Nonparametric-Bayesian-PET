from scipy.sparse import csr_matrix, lil_matrix

def build_prob_matrix_sparse(B_SQRT, D):
    """
    בונה את מטריצת ההסתברויות ישירות כפורמט Sparse לחיסכון אדיר בזיכרון.
    """
    B = B_SQRT**2
